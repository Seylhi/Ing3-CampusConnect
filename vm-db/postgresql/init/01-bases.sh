#!/bin/bash
set -e
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" <<EOSQL
CREATE USER acces WITH PASSWORD '$ACCES_PASSWORD';
CREATE DATABASE bdd_acces OWNER acces;
REVOKE CONNECT ON DATABASE bdd_acces FROM PUBLIC;

CREATE USER reservations WITH PASSWORD '$RESA_PASSWORD';
CREATE DATABASE bdd_reservations OWNER reservations;
REVOKE CONNECT ON DATABASE bdd_reservations FROM PUBLIC;
EOSQL
